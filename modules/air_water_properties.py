"""湿り空気と水の性質：温度・相対湿度・水蒸気圧・水分化学ポテンシャルの関係と、空気と水の値（計算方法の文書の評価方法「湿り空気と水の性質」）。

各値のコメントは、1 行目に「名前 記号, 単位」（無次元は -）、2 行目に「式 (k)」と補足を書く。
コメントの「式 (k)」は、計算方法の文書の「湿り空気と水の性質」（docs/source/contents/03_02_eval_air_water.md）の式の番号。
定数の名前は、その節の記号に合わせる（例：R_v は R_V、c_a は C_A）。
"""

import math


T_0 = 273.15
"""セルシウス温度と熱力学温度の差 T_0, K（T = θ + T_0。注意事項の「単位」）"""

R_V = 461.5
"""水蒸気の気体定数 R_v, J/(kg K)（3 節の表）"""

L_V = 2.512e6
"""水の蒸発潜熱 L_v, J/kg（3 節の表）"""

C_W = 4200.0
"""水の比熱 c_w, J/(kg K)（3 節の表）"""

RHO_W = 998.0
"""水の密度 ρ_w, kg/m3（3 節の表）"""

C_A = 1005.0
"""空気の比熱 c_a, J/(kg K)（3 節の表）"""


def get_p_vs(t: float) -> float:
    """飽和水蒸気圧 p_vs を求める。

    Args:
        t: 温度 T, K

    Returns:
        飽和水蒸気圧 p_vs, Pa

    Notes:
        計算方法の文書の「湿り空気と水の性質」の式 (1) に対応する。
    """

    # 飽和水蒸気圧 p_vs, Pa
    # 式 (1)
    p_vs = math.exp(-6096.938 / t + 21.2409642 - 2.711193e-2 * t + 1.673952e-5 * t ** 2 + 2.433502 * math.log(t))

    return p_vs


def get_mu(rh: float, t: float) -> float:
    """相対湿度から水分化学ポテンシャル μ を求める。

    Args:
        rh: 相対湿度 φ, %（0 より大きく 100 以下）
        t: 温度 T, K

    Returns:
        水分化学ポテンシャル μ, J/kg

    Notes:
        計算方法の文書の「湿り空気と水の性質」の式 (2) に対応する。
    """

    # 水分化学ポテンシャル μ, J/kg
    # 式 (2)
    mu = R_V * t * math.log(rh / 100.0)

    return mu


def get_rh(mu: float, t: float) -> float:
    """水分化学ポテンシャルから相対湿度 φ を求める。

    Args:
        mu: 水分化学ポテンシャル μ, J/kg
        t: 温度 T, K

    Returns:
        相対湿度 φ, %（100 を超えない）

    Notes:
        計算方法の文書の「湿り空気と水の性質」の式 (3) に対応する。
    """

    # 相対湿度 φ, %
    # 式 (3)。μ > 0 のときも 100 を超えないようにする
    rh = min(100.0 * math.exp(mu / (R_V * t)), 100.0)

    return rh


def get_rho_a(t: float) -> float:
    """空気の密度 ρ_a を求める。

    Args:
        t: 温度 T, K

    Returns:
        空気の密度 ρ_a, kg/m3

    Notes:
        計算方法の文書の「湿り空気と水の性質」の式 (6) に対応する。
    """

    # 空気の密度 ρ_a, kg/m3
    # 式 (6)
    rho_a = 353.0 / t

    return rho_a
